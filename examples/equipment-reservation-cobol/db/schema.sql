-- Equipment Reservation DB2 for z/OS schema.
-- All timestamps are stored as UTC TIMESTAMP values.

CREATE TABLE EQP_ACTR (
    ACTOR_ID        CHAR(12)       NOT NULL,
    EMPLOYEE_ROLE   CHAR(1)        NOT NULL,
    CUSTODIAN_ROLE  CHAR(1)        NOT NULL,
    PRIMARY KEY (ACTOR_ID)
);

CREATE TABLE EQP_EQUIP (
    EQUIP_ID        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    EQUIP_NAME      VARCHAR(40)    NOT NULL,
    EQUIP_DESC      VARCHAR(120)  NOT NULL,
    PRIMARY KEY (EQUIP_ID),
    CONSTRAINT EQP_EQUIP_NAME_UQ UNIQUE (EQUIP_NAME)
);

CREATE TABLE EQP_RSRVN (
    RSRV_ID         INTEGER GENERATED BY DEFAULT AS IDENTITY,
    EQUIP_ID        INTEGER        NOT NULL,
    ACTOR_ID        CHAR(12)       NOT NULL,
    RSRV_START      TIMESTAMP      NOT NULL,
    RSRV_END        TIMESTAMP      NOT NULL,
    RSRV_STATE      CHAR(10)       NOT NULL,
    PRIMARY KEY (RSRV_ID),
    CONSTRAINT EQP_RSRVN_EQUIP_FK FOREIGN KEY (EQUIP_ID)
        REFERENCES EQP_EQUIP (EQUIP_ID),
    CONSTRAINT EQP_RSRVN_STATE_CK CHECK
        (RSRV_STATE IN ('CONFIRMED', 'INVALID', 'CANCELLED', 'COMPLETED')),
    CONSTRAINT EQP_RSRVN_PERIOD_CK CHECK (RSRV_END > RSRV_START)
);

CREATE TABLE EQP_MAINT (
    MAINT_ID        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    EQUIP_ID        INTEGER        NOT NULL,
    MAINT_START     TIMESTAMP      NOT NULL,
    MAINT_END       TIMESTAMP      NOT NULL,
    MAINT_REASON    VARCHAR(80)    NOT NULL,
    PRIMARY KEY (MAINT_ID),
    CONSTRAINT EQP_MAINT_EQUIP_FK FOREIGN KEY (EQUIP_ID)
        REFERENCES EQP_EQUIP (EQUIP_ID),
    CONSTRAINT EQP_MAINT_PERIOD_CK CHECK (MAINT_END > MAINT_START)
);

CREATE TABLE EQP_USE (
    USE_ID          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    RSRV_ID         INTEGER        NOT NULL,
    EQUIP_ID        INTEGER        NOT NULL,
    ACTOR_ID        CHAR(12)       NOT NULL,
    PICKUP_TS       TIMESTAMP      NOT NULL,
    RETURN_TS       TIMESTAMP,
    PRIMARY KEY (USE_ID),
    CONSTRAINT EQP_USE_RSRV_FK FOREIGN KEY (RSRV_ID)
        REFERENCES EQP_RSRVN (RSRV_ID),
    CONSTRAINT EQP_USE_EQUIP_FK FOREIGN KEY (EQUIP_ID)
        REFERENCES EQP_EQUIP (EQUIP_ID),
    CONSTRAINT EQP_USE_RSRV_UQ UNIQUE (RSRV_ID)
);

CREATE INDEX EQP_RSRVN_EQUIP_IX
    ON EQP_RSRVN (EQUIP_ID, RSRV_START, RSRV_END);

CREATE INDEX EQP_MAINT_EQUIP_IX
    ON EQP_MAINT (EQUIP_ID, MAINT_START, MAINT_END);

CREATE INDEX EQP_USE_EQUIP_IX
    ON EQP_USE (EQUIP_ID, USE_ID);

